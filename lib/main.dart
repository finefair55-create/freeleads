/// Firebase is initialized only on supported platforms. Linux desktop skips
/// the plugin entirely (FlutterFire has no Linux implementation) so startup
/// cannot crash with MissingPluginException / [core/no-app].
///
/// Options come from `lib/firebase_options.dart` (git-ignored), generated by
/// `flutterfire configure`. See `lib/firebase_options.example.dart`.
Future<void> main() async {
  await runZonedGuarded(
    () async {
      WidgetsFlutterBinding.ensureInitialized();
      FlutterError.onError = (details) {
        FlutterError.dumpErrorToConsole(details, forceReport: true);
      };
      ErrorWidget.builder = (details) {
        return const ColoredBox(
          color: Color(0xFFF4F7F6),
          child: Center(
            child: Padding(
              padding: EdgeInsets.all(24),
              child: Text(
                'This panel could not be rendered. The rest of the app is still running.',
                textAlign: TextAlign.center,
              ),
            ),
          ),
        );
      };
      PlatformDispatcher.instance.onError = (error, stack) {
        debugPrint('Uncaught platform error: $error');
        debugPrintStack(stackTrace: stack);
        return true;
      };

      final results = await Future.wait<Object>([
        initializeFirebaseSafely(),
        LocalLeadStore.open(),
      ]);
      final store = results[1] as LocalLeadStore;
      final repository = LeadRepository(
        local: store,
        community: FirestoreService(),
        // The store remembers host pauses across restarts.
        pipeline: ListingPipeline(
          sources: ListingPipeline.defaultSources(cooldowns: store),
        ),
      )..start();
      runApp(FreeLeadsApp(repository: repository));
    },
    (error, stack) {
      debugPrint('Uncaught async error: $error');
      debugPrintStack(stackTrace: stack);
    },
  );
}

Future<bool> initializeFirebaseSafely() async {
  if (!isFirebasePlatformSupported) {
    debugPrint('Skipping Firebase on ${defaultTargetPlatform.name}.');
    return false;
  }
  try {
    if (Firebase.apps.isNotEmpty) {
      return true;
    }
    // Read only after the platform check: currentPlatform throws on Linux.
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    ).timeout(const Duration(seconds: 6));
    return Firebase.apps.isNotEmpty;
  } catch (error, stackTrace) {
    debugPrint('Firebase init skipped: $error');
    debugPrintStack(stackTrace: stackTrace);
    return false;
  }
}
